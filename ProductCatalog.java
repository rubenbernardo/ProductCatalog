	public static ProductItem findProduct(
			String title,
			String productType,
			String category
	) {

		List<ProductItem> products;

		if (
				category != null
				&&
				category.equals(
						"Business & Entrepreneurship"
				)
		) {

			products =
					getBusinessProducts();

		} else {

			products =
					new ArrayList<>();
		}


		for (ProductItem product : products) {

			if (
					product.title.equals(title)
					&&
					product.productType.equals(productType)
					&&
					product.category.equals(category)
			) {

				return product;
			}
		}

		return null;
	}
